-- New and changed alerts.
--
-- event_changes is a log the database writes itself: "new" when an event is
-- first published, "updated" when a published event changes in a way people
-- care about (cancelled or restored, time, place, call for speakers, access).
-- Each row keeps a snapshot of what was true then.
--
-- Delivery is exact:
--  - Rows get their order number (seq) only from sequence_changes(), which
--    numbers rows once they're visible (committed). A transaction that
--    commits late can't slip behind a subscriber's cursor.
--  - queue_alert moves a subscriber's cursor and queues the email together,
--    and only if the subscriber is still confirmed, not suppressed, on the
--    same cadence and the same preferences.
--  - A subscriber's cursor starts when an alert subscription starts (on
--    confirming, or switching to daily or instant).

create table public.event_changes (
  id bigint generated by default as identity primary key,
  seq bigint unique,
  event_id uuid not null references public.events (id) on delete cascade,
  kind text not null check (kind in ('new', 'updated')),
  what text[] not null default '{}' check (what <@ array['cancelled', 'restored', 'time', 'place', 'cfp', 'access']),
  before_status public.event_status,
  after jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index event_changes_unsequenced on public.event_changes (id) where seq is null;
create index event_changes_created on public.event_changes (created_at);
create index event_changes_event on public.event_changes (event_id);

create sequence public.event_change_seq;

-- Numbers every visible change that has no number yet, in id order. Run at
-- the start of each alert run; only one at a time.
create function public.sequence_changes()
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  r record;
begin
  perform pg_catalog.pg_advisory_xact_lock(hashtext('calenda11y:sequence_changes'));
  for r in select id from public.event_changes where seq is null order by id for update loop
    update public.event_changes set seq = pg_catalog.nextval('public.event_change_seq') where id = r.id;
  end loop;
  return coalesce((select max(seq) from public.event_changes), 0);
end;
$$;

create function public.events_log_changes()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_what text[] := '{}';
  v_after jsonb;
begin
  v_after := jsonb_build_object(
    'status', new.status, 'all_day', new.all_day, 'starts_at', new.starts_at, 'ends_at', new.ends_at,
    'start_date', new.start_date, 'end_date', new.end_date, 'timezone', new.timezone,
    'local_start_date', new.local_start_date, 'local_end_date', new.local_end_date,
    'format', new.format, 'venue', new.venue, 'city', new.city, 'country_code', new.country_code,
    'cfp_url', new.cfp_url, 'cfp_closes_on', new.cfp_closes_on, 'cfp_last_day', new.cfp_last_day,
    'cfp_capped', new.cfp_capped,
    'captions', new.captions, 'sign_language', new.sign_language, 'step_free', new.step_free,
    'quiet_room', new.quiet_room, 'hearing_loop', new.hearing_loop, 'remote_attendance', new.remote_attendance
  );

  -- First published.
  if new.approved_at is not null and (tg_op = 'INSERT' or old.approved_at is null) then
    insert into public.event_changes (event_id, kind, before_status, after)
    values (new.id, 'new', case when tg_op = 'UPDATE' then old.status end, v_after);
    return null;
  end if;

  -- Material changes to an event that was and still is public. Unpublishing
  -- and republishing log nothing.
  if tg_op = 'UPDATE' and old.status in ('approved', 'cancelled') and new.status in ('approved', 'cancelled') then
    if old.status = 'approved' and new.status = 'cancelled' then v_what := pg_catalog.array_append(v_what, 'cancelled'); end if;
    if old.status = 'cancelled' and new.status = 'approved' then v_what := pg_catalog.array_append(v_what, 'restored'); end if;
    if (new.all_day, new.starts_at, new.ends_at, new.start_date, new.end_date, new.timezone)
       is distinct from (old.all_day, old.starts_at, old.ends_at, old.start_date, old.end_date, old.timezone) then
      v_what := pg_catalog.array_append(v_what, 'time');
    end if;
    if (new.format, new.country_code, new.city, new.venue) is distinct from (old.format, old.country_code, old.city, old.venue) then
      v_what := pg_catalog.array_append(v_what, 'place');
    end if;
    if (new.cfp_url, new.cfp_closes_on) is distinct from (old.cfp_url, old.cfp_closes_on) then
      v_what := pg_catalog.array_append(v_what, 'cfp');
    end if;
    if (new.captions, new.sign_language, new.step_free, new.quiet_room, new.hearing_loop, new.remote_attendance)
       is distinct from (old.captions, old.sign_language, old.step_free, old.quiet_room, old.hearing_loop, old.remote_attendance) then
      v_what := pg_catalog.array_append(v_what, 'access');
    end if;
    if cardinality(v_what) > 0 then
      insert into public.event_changes (event_id, kind, what, before_status, after)
      values (new.id, 'updated', v_what, old.status, v_after);
    end if;
  end if;
  return null;
end;
$$;

create trigger events_log_changes
after insert or update on public.events
for each row execute function public.events_log_changes();

-- Rounds: each send works up to a fixed point (snapshot_seq). A run cut
-- short continues the same round, so nobody gets two emails in one round.
create table public.alert_rounds (
  id uuid primary key default gen_random_uuid(),
  cadence public.digest_cadence not null check (cadence in ('daily', 'instant')),
  -- The UTC day, for daily rounds (one a day).
  round_date date,
  snapshot_seq bigint not null,
  status text not null default 'running' check (status in ('running', 'complete')),
  counts jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  check ((cadence = 'daily') = (round_date is not null))
);

create unique index alert_rounds_daily on public.alert_rounds (round_date) where cadence = 'daily';
create unique index alert_rounds_one_running on public.alert_rounds (cadence) where status = 'running';
create index alert_rounds_recent on public.alert_rounds (cadence, started_at desc);

alter table public.digest_subscribers
  add column alert_cursor bigint,
  add column prefs_revision integer not null default 1;

-- Keeps alert subscriptions consistent however they're saved: a preference
-- change bumps the revision (so work prepared before it is refused), and an
-- alert subscription starting (confirmed, or switched to daily or instant)
-- sets its cursor to "now". Switching away clears it.
create function public.digest_subscribers_before_write()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_alerts boolean := new.cadence in ('daily', 'instant');
  v_starting boolean;
begin
  if tg_op = 'UPDATE' and (new.cadence, new.countries, new.formats, new.types, new.topics, new.include_cfp)
     is distinct from (old.cadence, old.countries, old.formats, old.types, old.topics, old.include_cfp) then
    new.prefs_revision := old.prefs_revision + 1;
  end if;
  if not v_alerts then
    new.alert_cursor := null;
    return new;
  end if;
  v_starting := new.confirmed_at is not null and (
    tg_op = 'INSERT'
    or old.confirmed_at is null
    or old.cadence is distinct from new.cadence
  );
  if v_starting then
    new.alert_cursor := coalesce((select max(seq) from public.event_changes), 0);
  end if;
  return new;
end;
$$;

create trigger digest_subscribers_before_write
before insert or update on public.digest_subscribers
for each row execute function public.digest_subscribers_before_write();

-- Moves a subscriber's cursor and queues their alert, together, only if
-- nothing about them changed since the work was prepared. A null email
-- moves the cursor without sending (nothing matched).
create function public.queue_alert(
  p_subscriber uuid,
  p_cadence public.digest_cadence,
  p_revision integer,
  p_from bigint,
  p_to bigint,
  p_email jsonb
)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  update public.digest_subscribers
  set alert_cursor = p_to
  where id = p_subscriber
    and cadence = p_cadence
    and prefs_revision = p_revision
    and confirmed_at is not null
    and suppressed_at is null
    and alert_cursor is not distinct from p_from;
  if not found then
    return false;
  end if;
  if p_email is not null then
    perform public.enqueue_emails(jsonb_build_array(p_email));
  end if;
  return true;
end;
$$;

-- Older rows (if any) with an alert cadence and no cursor start from now.
update public.digest_subscribers
set alert_cursor = coalesce((select max(seq) from public.event_changes), 0)
where cadence in ('daily', 'instant') and confirmed_at is not null and alert_cursor is null;

